import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../src/lib/stageCapacity.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } });
const sandbox = { exports: {} }; vm.runInNewContext(outputText, sandbox);
const { allStageDaysFull, blockedStageDays, countStageDays, emptyStageDays, isStageDayFull, stageRegistrationError } = sandbox.exports;
const counts = { monday: 16, tuesday: 9, wednesday: 8, thursday: 10, friday: 9 };
assert.equal(allStageDaysFull(counts, 16), false);
assert.equal(isStageDayFull(counts, 16, 'monday'), true);
assert.equal(isStageDayFull(counts, 16, 'tuesday'), false);
assert.equal(isStageDayFull(counts, null, 'monday'), false);
assert.equal(isStageDayFull(undefined, 16, 'monday'), false);
assert.equal(blockedStageDays({ ...emptyStageDays(), tuesday: true }, counts, 16).length, 0);
assert.equal(blockedStageDays({ ...emptyStageDays(), monday: true, tuesday: true }, counts, 16).length, 1);
assert.equal(allStageDaysFull({ monday:16, tuesday:16, wednesday:16, thursday:16, friday:16 },16),true);
assert.equal(allStageDaysFull(counts,null),false);
const rows = Array.from({length:20},(_,i)=>({...emptyStageDays(),monday:i<10,tuesday:i>=10}));
const totals = countStageDays(rows);
assert.equal(totals.monday,10); assert.equal(totals.tuesday,10);
assert.equal(allStageDaysFull(totals,16),false,'20 inscrits répartis sur deux jours ne rendent pas le stage complet');
assert.equal(stageRegistrationError({code:'23514',message:'Journée complète : lundi'}),'Journée complète : lundi');
assert.notEqual(stageRegistrationError({code:'23514',message:'stage_at_least_one_day'}),'Ce stage est complet.');
console.log('OK : capacité par jour, sélection partielle, illimité et erreurs précises.');
