import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { izonFaqs, izonHeading, izonIntro, izonMetadata, izonPagePath, izonSections } from '../src/data/izonSeo.mjs';
import { clubAddress, directionsFrom, localPagePath, localTowns } from '../src/data/localSeo.mjs';
const read = path => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
const html = await read(`dist${izonPagePath}/index.html`);
assert.equal((html.match(/<h1>/g) ?? []).length, 1);
for (const text of [izonHeading, izonIntro, izonMetadata.title, izonMetadata.description, clubAddress, ...izonSections.flatMap(s => [s.title, s.text]), ...izonFaqs.flatMap(f => [f.question, f.answer])]) assert.ok(html.includes(text), `Texte manquant : ${text}`);
assert.ok(html.includes(`rel="canonical" href="https://www.saintloubping.fr${izonPagePath}"`));
assert.ok(html.includes('content="index,follow,max-image-preview:large"'));
for (const path of ['/essai-gratuit', '/horaires', '/adhesions', '/contact', localPagePath]) assert.ok(html.includes(`href="${path}"`));
assert.match(html, /09h30 – 11h00/);
assert.match(html, /19h30 – 21h00/);
assert.ok((await read('dist/sitemap.xml')).includes(`https://www.saintloubping.fr${izonPagePath}`));
assert.ok((await read(`dist${localPagePath}/index.html`)).includes(`href="${izonPagePath}"`));
for (const path of ['src/components/Footer.tsx', 'src/pages/TennisLocal.tsx', 'src/App.tsx']) assert.ok((await read(path)).includes(izonPagePath));
const itinerary = new URL(directionsFrom('Izon'));
assert.equal(itinerary.searchParams.get('origin'), 'Izon, Gironde, France');
assert.equal(itinerary.searchParams.get('destination'), clubAddress);
assert.equal(localTowns.length, 6, 'Ne pas intégrer Izon aux Rives de la Laurence');
const schema = JSON.parse(html.match(/id="club-structured-data" type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
assert.equal(schema.address.addressLocality, 'Saint-Loubès');
console.log('OK : page Izon pré-rendue, contenu, horaires, adresse réelle, liens internes, métadonnées et sitemap.');
